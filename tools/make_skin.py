FONT = os.path.join(OUT, "fonts")
Y86, W, H = 86, 1280, 628
RED, SLATE, BODY, WHITE, INK = (195, 28, 43), (106, 110, 150), (168, 164, 168), (255, 255, 255), (32, 32, 48)
KNOB = 84

PARAMS = {p["key"]: p for p in json.load(open(os.path.join(OUT, "params.json")))["params"]}
_f = {}
def F(size, face="LiberationSans-Bold.ttf"):
    if (size, face) not in _f:
        _f[(size, face)] = ImageFont.truetype(os.path.join(FONT, face), size)
    return _f[(size, face)]
TITLE = "LiberationSans-BoldItalic.ttf"

LOGO = Image.open(os.path.join(PARTS, "logo.png")).convert("RGB")
lines = []
emit = lines.append


class Page:
    def __init__(self, name, qkeys, *more):
        self.name, self.qkeys, self.more = name, qkeys, more
        self.im = Image.new("RGB", (W, H), RED)
        self.d = ImageDraw.Draw(self.im)
        self.widgets = []

    def chip(self, cx, y, text, size=17):
        """a label on a slate pill (the skin's own), centred at cx, top at y"""
        f = F(size)
        tw = int(self.d.textlength(text, font=f))
        self.d.rounded_rectangle((cx - tw // 2 - 10, y - 3, cx + tw // 2 + 10, y + size + 4), (size + 7) // 2, fill=SLATE)
        self.d.text((cx, y), text, font=f, fill=WHITE, anchor="ma")

    def panel(self, x, y, w, h, title=None):
        """a section: light grey body under a slate title bar with a white italic title"""
        self.d.rounded_rectangle((x, y, x + w, y + h), 10, fill=BODY)
        if title:
            self.d.rounded_rectangle((x, y, x + w, y + 30), 10, fill=SLATE)
            self.d.rectangle((x, y + 16, x + w, y + 30), fill=SLATE)
            self.d.text((x + 14, y + 3), title, font=F(21, TITLE), fill=WHITE)

    def label(self, cx, y, s, size=16):
        self.chip(cx, y, s, size)

    def ctl(self, cx, cy, key, label, w=None):
        """the right live widget for the parameter: knob (a number), toggle (two options), popup (more)"""
        p = PARAMS[key]
        opts = p.get("options")
        if opts and len(opts) == 2:
            self.label(cx, cy - 44, label)
            self.widgets.append('toggle cx=%d cy=%d label="" key=%s ns=0' % (cx, cy + Y86, key))
        elif opts:
            w = w or 150
            self.label(cx, cy - 46, label)
            self.widgets.append('popup cx=%d cy=%d w=%d h=34 label="" key=%s' % (cx, cy + Y86 - 2, w, key))
        else:
            self.label(cx, cy - KNOB // 2 - 26, label)
            self.widgets.append('knob cx=%d cy=%d r=%d label="" key=%s ns=0 vs=22 vy=14 bw=%d' % (cx, cy + Y86, KNOB // 2 - 8, key, KNOB + 26))

    def small_knob(self, cx, cy, key, label):
        self.label(cx, cy - 58, label, 14)
        self.widgets.append('knob cx=%d cy=%d r=%d label="" key=%s ns=0 vs=18 vy=10 bw=%d' % (cx, cy + Y86, 30, key, 118))

    def row(self, x0, x1, y, items):
        cw = (x1 - x0) / len(items)
        for i, it in enumerate(items):
            if it:
                self.ctl(int(x0 + cw * (i + 0.5)), y, it[0], it[1], min(int(cw) - 10, 190))

    def button(self, cx, cy, key, label):
        self.widgets.append('button cx=%d cy=%d label="%s" key=%s' % (cx, cy + Y86, label, key))

    def done(self):
        fn = "images/page_%s.png" % re.sub(r"[^A-Za-z0-9]+", "_", self.name)
        self.im.save(os.path.join(OUT, fn))
        emit("")
        emit("[tab %s]" % self.name)
        emit('art x=0 y=%d w=%d h=%d file="%s"' % (Y86, W, H, fn))
        lines.extend(self.widgets)
        emit('qlinks "%s" = %s' % (self.name, ",".join(self.qkeys)))
        for title, keys in self.more:
            emit('qlinks "%s" = %s' % (title, ",".join(keys)))


